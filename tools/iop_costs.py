"""Builds config/iop/yysound_costs.h from PS2X_IOP_VERIFY run logs.

usage: python tools/iop_costs.py LOG [LOG...]

Each log has, per replaced function, a line like
  [iop:native] atick_resume: 28160 call(s), 174 verified, 0 mismatch(es), 0 not verifiable, the original takes 4317 instruction(s) on average (120 in imports)
The cost of a function is what the original takes minus what it spends inside its imports (a replacement runs the imports itself, so
those instructions are counted when it does). For each function the line with the most verified calls over all the logs is used.
A replacement charges this much IOP time when the IOP enters it from guest code, which keeps timers and DMA completions on the
schedule the original gave them (an average: the original's count depends on the data).
"""
import os
import re
import sys

LINE = re.compile(r"\[iop:native\] (\w+): (\d+) call\(s\), (\d+) verified, (\d+) mismatch\(es\), (\d+) not verifiable, "
                  r"the original takes (\d+) instruction\(s\) on average \((\d+) in imports\)")


def main(paths):
    best = {}
    for path in paths:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            text = handle.read()
        for match in LINE.finditer(text):
            name, calls, verified, mismatches, _unverifiable, total, imports = match.groups()
            verified = int(verified)
            if verified == 0:
                continue
            if name not in best or verified > best[name][0]:
                best[name] = (verified, int(total), int(imports), int(mismatches))
    rows = []
    for name in sorted(best):
        verified, total, imports, mismatches = best[name]
        rows.append((name, max(total - imports, 0), verified, total, imports, mismatches))
    out = []
    out.append("// Generated by tools/iop_costs.py from PS2X_IOP_VERIFY run logs; do not edit.")
    out.append("// The IOP instructions each replaced function of YYSOUND takes in the original, imports not counted, averaged over the verified calls")
    out.append("// (name, cost, verified calls). The port charges this much IOP time when the IOP enters the function from guest code.")
    out.append("")
    out.append("#pragma once")
    out.append("")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace iop::yysound")
    out.append("{")
    out.append("    struct FunctionCost")
    out.append("    {")
    out.append("        const char *name;")
    out.append("        uint32_t cost;")
    out.append("        uint32_t verified;")
    out.append("    };")
    out.append("")
    out.append("    inline constexpr FunctionCost kCosts[] = {")
    for name, cost, verified, _total, _imports, _mismatches in rows:
        out.append('        {"%s", %d, %d},' % (name, cost, verified))
    out.append("        {nullptr, 0, 0}, // end of the table")
    out.append("    };")
    out.append("}")
    out.append("")
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "config", "iop", "yysound_costs.h")
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    print("wrote %s: %d functions" % (os.path.normpath(target), len(rows)))
    bad = [r for r in rows if r[5] != 0]
    if bad:
        print("warning: mismatches in the logs for", ", ".join(r[0] for r in bad))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    main(sys.argv[1:])
