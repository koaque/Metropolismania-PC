#!/usr/bin/env python3
"""Write docs/map/<subsystem>.md from config/port_status.csv.

usage: map_docs.py --root ROOT

Each page has a hand-written part (overview, structs, globals) above the marker line and a
generated function table below it. Only the part below the marker is rewritten, so edit the
overview freely and keep function notes in config/port_status.csv (tools/map_apply.py).
SDK subsystems (sdk:<lib>) share one page, docs/map/sdk.md, grouped by library.
docs/map/README.md is generated whole.
"""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path

MARKER = "<!-- Generated below by tools/map_docs.py from config/port_status.csv. Edit function notes there, not here. -->"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def table(rows: list[dict[str, str]]) -> list[str]:
    lines = ["| Address | Name | Size | Blocks | Notes |", "|---|---|---:|---|---|"]
    for r in rows:
        lines.append(f"| `{r['address']}` | `{r['name']}` | {r['size']} | {r['blocking']} | {cell(r['notes'])} |")
    return lines


def summary(rows: list[dict[str, str]]) -> str:
    n = len(rows)
    block = sum(1 for r in rows if r["blocking"] == "yes")
    indirect = sum(1 for r in rows if r["blocking"] == "indirect")
    status = defaultdict(int)
    for r in rows:
        status[r["status"]] += 1
    done = ", ".join(f"{k} {v}" for k, v in sorted(status.items()))
    return (f"{n} functions ({done}). Blocks: {block} can reach a thread switch, {indirect} make indirect "
            f"calls that were not followed; both wait for native threading (P6) before porting.")


def write_page(path: Path, title: str, body: list[str]) -> None:
    hand = f"# {title}\n\nOverview not written yet.\n"
    if path.exists():
        text = path.read_text(encoding="utf-8")
        hand = text.split(MARKER, 1)[0] if MARKER in text else text
    out = hand.rstrip("\n") + "\n\n" + MARKER + "\n\n" + "\n".join(body) + "\n"
    path.write_text(out, encoding="utf-8", newline="\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    args = ap.parse_args()
    root = Path(args.root)
    with (root / "config/port_status.csv").open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))

    by_sub: dict[str, list[dict[str, str]]] = defaultdict(list)
    sdk: dict[str, list[dict[str, str]]] = defaultdict(list)
    for r in rows:
        sub = r["subsystem"] or ("sdk:signature-scan" if r["origin"] == "sdk" else "unclassified")
        if sub.startswith("sdk"):
            sdk[sub.split(":", 1)[1] if ":" in sub else "other"].append(r)
        else:
            by_sub[sub].append(r)

    out_dir = root / "docs/map"
    out_dir.mkdir(parents=True, exist_ok=True)
    index = [
        "# Function map",
        "",
        "Generated by `tools/map_docs.py` (`pipeline.py status`); do not edit by hand.",
        "One page per subsystem: a hand-written overview, then every function with its notes.",
        "Addresses are for SLUS_203.77 (CRC32 `4FA3F727`). Status and progress: [PORT_STATUS.md](../PORT_STATUS.md).",
        "",
        "| Subsystem | Functions | Can block |",
        "|---|---:|---:|",
    ]
    for sub in sorted(by_sub):
        items = sorted(by_sub[sub], key=lambda r: int(r["address"], 16))
        write_page(out_dir / f"{sub}.md", sub, ["## Functions", "", summary(items), ""] + table(items))
        block = sum(1 for r in items if r["blocking"] == "yes")
        index.append(f"| [{sub}]({sub}.md) | {len(items)} | {block} |")

    body = ["## Functions by library", ""]
    total = 0
    for lib in sorted(sdk):
        items = sorted(sdk[lib], key=lambda r: int(r["address"], 16))
        total += len(items)
        body += [f"### {lib}", "", summary(items), ""] + table(items) + [""]
    write_page(out_dir / "sdk.md", "SDK", body)
    index.append(f"| [sdk](sdk.md) | {total} | - |")
    (out_dir / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8", newline="\n")
    print(f"[map_docs] {len(by_sub)} subsystem pages and sdk.md written to docs/map/")


if __name__ == "__main__":
    main()
