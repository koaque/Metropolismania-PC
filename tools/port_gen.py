#!/usr/bin/env python3
"""Generate the readable port's headers from the game's types and prototypes.

usage: port_gen.py [--check]

  src/port/game_types.h      config/types/*.h as C++ overlays on guest memory: pointer fields become
                             mm::GuestPtr<T> (32 bits, as on the EE), float fields mm::ps2f; every
                             "+0xNN" field comment and "(0xNN bytes)" struct note becomes a static_assert.
  src/port/game_functions.h  one entry per line of config/signatures.txt: mm::addr::<Name> (the address),
                             and mm::<Name> (the game name without "mm_"). A function that src/port/ ports
                             (a PORT_FN(<Name>) line) is only declared; every other one gets an inline
                             body that calls the generated function through the runtime's function table.

Pointer parameters are host pointers in C++ (the wrapper converts guest addresses), float parameters
and float pointees are mm::ps2f. tools/pipeline.py stage runs this before copying src/port/.
--check exits 1 when a header is out of date instead of writing it.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TYPES = ROOT / "config/types"
PORT = ROOT / "src/port"

FIELD = re.compile(r"^(?P<indent>\s*)(?P<type>(?:const\s+)?[A-Za-z_]\w*)\s*(?P<ptr>\*?)\s*(?P<name>\w+)(?P<arr>(?:\[[^\]]+\])*);(?P<rest>.*)$")
NAMED = re.compile(r"^\s+[A-Za-z_][\w ]*?[\s*]+(?P<name>\w+)(\[[^\]]+\])*;\s*/\*\s*\+(?P<off>0x[0-9A-Fa-f]+)")
STRUCT_OPEN = re.compile(r"^struct (\w+) \{\s*$")
STRUCT_LINE = re.compile(r"^struct (\w+) \{(.*)\};(.*)$")
TYPEDEF = re.compile(r"^typedef struct (\w+) \1;\s*$")
SIZE = re.compile(r"\((0x[0-9A-Fa-f]+) bytes")

KEYWORDS = {"new", "delete", "this", "class", "template", "typename", "private", "public", "protected",
            "operator", "friend", "virtual", "register", "default", "export", "mutable", "namespace"}

HEADER = "// Generated by tools/port_gen.py from {src}; do not edit.\n"


def field_cpp(line: str) -> str:
    m = FIELD.match(line)
    if not m:
        return line
    t = m.group("type")
    if m.group("ptr"):
        t = f"GuestPtr<{t}>"
    elif t == "float":
        t = "ps2f"
    return f"{m.group('indent')}{t} {m.group('name')}{m.group('arr')};{m.group('rest')}"


def gen_types() -> tuple[str, set[str]]:
    out = [HEADER.format(src="config/types/*.h"), "#pragma once", "", '#include "guest.h"', "", "#include <cstddef>",
           "", "namespace mm", "{"]
    asserts: list[str] = []
    structs: set[str] = set()
    for header in sorted(TYPES.glob("*.h")):
        if header.name.startswith("00_"):
            continue  # C base types; <cstdint> has them
        out.append(f"// ---- {header.name}")
        current = None
        last_comment = ""
        for line in header.read_text(encoding="utf-8").splitlines():
            stripped = line.strip()
            if m := TYPEDEF.match(line):
                out.append(f"struct {m.group(1)};")
                continue
            if m := STRUCT_LINE.match(line):
                name, body, rest = m.groups()
                structs.add(name)
                size = SIZE.search(last_comment)
                if size:
                    asserts.append(f"static_assert(sizeof({name}) == {size.group(1)}, \"{name} size\");")
                fields = " ".join(field_cpp(f.strip() + ";") for f in body.split(";") if f.strip())
                out.append(f"struct {name} {{ {fields} }};{rest}")
                last_comment = ""
                continue
            if m := STRUCT_OPEN.match(line):
                current = m.group(1)
                structs.add(current)
                size = SIZE.search(last_comment)
                if size:
                    asserts.append(f"static_assert(sizeof({current}) == {size.group(1)}, \"{current} size\");")
                out.append(line)
                continue
            if line.startswith("};"):
                current = None
                out.append(line)
                continue
            if stripped.startswith("/*"):
                last_comment = line
            elif stripped and not stripped.startswith("*"):
                last_comment = ""
            if current:
                n = NAMED.match(line)
                if n:
                    asserts.append(f"static_assert(offsetof({current}, {n.group('name')}) == {n.group('off')}, "
                                   f"\"{current}.{n.group('name')}\");")
                out.append(field_cpp(line))
            else:
                out.append(line)
        out.append("")
    out += ["// ---- layout checks (guest offsets and sizes)"] + asserts + ["}", ""]
    return "\n".join(out), structs


PROTO = re.compile(r"^(0x[0-9A-Fa-f]{8}) (.*?)\b(mm_\w+)\((.*)\);\s*$")


def cpp_type(ctype: str, structs: set[str]) -> str:
    t = " ".join(ctype.replace("*", " * ").split())
    base = t.replace(" *", "").strip()
    stars = t.count("*")
    if base == "float":
        base = "ps2f"
    return base + (" " + "*" * stars if stars else "")


def joined(ctype: str, name: str) -> str:
    return f"{ctype}{name}" if ctype.endswith("*") else f"{ctype} {name}"


def split_param(param: str) -> tuple[str, str]:
    m = re.match(r"^(.*?)(\w+)\s*$", param.strip())
    ctype, name = m.group(1).strip(), m.group(2)
    if name in KEYWORDS:
        name += "_"
    return ctype, name


def ported_names() -> set[str]:
    names = set()
    for cpp in PORT.rglob("*.cpp"):
        names |= set(re.findall(r"^\s*PORT_FN\((\w+)\)", cpp.read_text(encoding="utf-8"), re.M))
    return names


def gen_functions(structs: set[str]) -> str:
    sizes = {}
    with (ROOT / "config/port_status.csv").open(encoding="utf-8", newline="") as fh:
        for r in csv.DictReader(fh):
            sizes[int(r["address"], 16)] = int(r["size"] or 0)
    entries = []
    for line in (ROOT / "config/signatures.txt").read_text(encoding="utf-8").splitlines():
        m = PROTO.match(line)
        if m:
            entries.append((int(m.group(1), 16), m.group(2).strip(), m.group(3), m.group(4).strip()))
    # Ghidra shows a thunk under its target's name; the larger function keeps the plain name.
    by_name: dict[str, list[int]] = {}
    for addr, _, name, _ in entries:
        by_name.setdefault(name, []).append(addr)
    keep = {name: max(addrs, key=lambda a: sizes.get(a, 0)) for name, addrs in by_name.items()}
    ported = ported_names()

    out = [HEADER.format(src="config/signatures.txt"), "#pragma once", "", '#include "abi.h"', '#include "game_types.h"', "",
           "namespace mm", "{", "namespace addr", "{"]
    decls, bodies = [], []
    seen = set()
    for addr, ret, name, args in entries:
        cname = name[3:] if keep[name] == addr else f"{name[3:]}_{addr:X}"
        if cname in structs:
            cname += "_fn"
        if cname in seen:
            sys.exit(f"port_gen: duplicate function name {cname}")
        seen.add(cname)
        out.append(f"inline constexpr uint32_t {cname} = 0x{addr:08X}u;")
        params = [] if args in ("", "void") else [split_param(p) for p in args.split(",")]
        r = cpp_type(ret, structs)
        plist = ", ".join(joined(cpp_type(t, structs), n) for t, n in params)
        if cname in ported:
            decls.append(f"{joined(r, cname)}({plist});")
        else:
            call = ", ".join([f"addr::{cname}"] + [n for _, n in params])
            ret_kw = "" if r == "void" else "return "
            bodies.append(f"inline {joined(r, cname)}({plist}) {{ {ret_kw}port::callGuest<{r}>({call}); }}")
    missing = ported - seen
    if missing:
        sys.exit(f"port_gen: PORT_FN names without a prototype in config/signatures.txt: {', '.join(sorted(missing))}")
    table = [f'    {{"{n}", addr::{n}}},' for n in sorted(seen, key=lambda n: n)]
    out += ["}", "", "struct GameFunction", "{", "    const char *name;", "    uint32_t address;", "};",
            "inline constexpr GameFunction kGameFunctions[] = {"] + table + ["};", ""]
    out += ["// Ported (src/port/)."] + decls + ["", "// Not ported yet: the generated function, through the runtime's function table."] + bodies
    out += ["}", ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    types_text, structs = gen_types()
    files = {PORT / "game_types.h": types_text, PORT / "game_functions.h": gen_functions(structs)}
    stale = []
    for path, text in files.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path.name)
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if args.check and stale:
        sys.exit(f"port_gen: out of date: {', '.join(stale)}")
    print(f"[port_gen] {'checked' if args.check else 'wrote'} game_types.h and game_functions.h"
          f"{' (' + ', '.join(stale) + ' changed)' if stale else ' (unchanged)'}")


if __name__ == "__main__":
    main()
